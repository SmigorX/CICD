"""
Utility functions for basic arithmetic operations.
"""

def add (a: int , b: int) -> int :
    """
    Adding funciton
    :param a:
    :param b:
    :return:
    """
    return a + b

def subtract (a: int , b: int) -> int :
    """
    Subtracting funciton
    :param a:
    :param b:
    :return:
    """
    return a - b

def multiply (a: int , b: int) -> int :
    """
    Multiplying funciton
    :param a:
    :param b:
    :return:
    """
    return a * b

def divide ( a: int , b : int ) -> float :
    """
    Divide funciton
    :param a:
    :param b:
    :return:
    """
    return a / b
